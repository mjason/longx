import { chromium, devices } from "playwright";
const S = process.env.S;
const browser = await chromium.launch();
const shoot = async (ctx, name, phone) => {
  const page = await ctx.newPage();
  const problems = [];
  page.on("console", (m) => { if (["error", "warning"].includes(m.type())) problems.push(`${m.type()}: ${m.text().slice(0, 200)}`); });
  page.on("pageerror", (e) => problems.push(`pageerror: ${e.message}`));
  await page.goto("http://127.0.0.1:7788/p/数学精灵", { waitUntil: "networkidle" });
  await page.waitForTimeout(1500);
  await page.goto("http://127.0.0.1:7788/p/数学精灵", { waitUntil: "networkidle" });
  await page.waitForTimeout(1200);
  if (phone) await page.getByRole("button", { name: /文件/ }).click(); else await page.keyboard.press("Meta+6");
  await page.waitForTimeout(1200);
  await page.screenshot({ path: `${S}/${name}-tree.png` });
  const readme = page.getByRole("treeitem", { name: /README/i }).first();
  await readme.click();
  await page.waitForTimeout(2500);
  await page.screenshot({ path: `${S}/${name}-editor.png` });
  const wide = await page.evaluate(() => [...document.querySelectorAll("*")].filter((el) => el.getBoundingClientRect().right > document.documentElement.clientWidth + 1).slice(0, 3).map((el) => el.tagName + "." + [...el.classList].slice(0, 3).join(".")));
  console.log(name, JSON.stringify({ wide, problems: problems.slice(0, 4) }));
  await page.close();
};
await shoot(await browser.newContext({ viewport: { width: 1280, height: 860 } }), "desk", false);
await shoot(await browser.newContext({ ...devices["iPhone 13"] }), "phone", true);
await browser.close();
