// The GraphQL client's two generated inputs, from the schema Longx writes on
// every compilation (priv/schema.graphql):
//
//   js/core/operations.graphql — one operation per root field, selecting every
//     scalar and every nested map type of its result (a relationship to
//     another resource is left out: a list page never loads rows behind rows;
//     a hook that needs one writes its own document);
//   js/core/api.ts — one function per operation, named like the root field,
//     in the shape the hooks and the tests call: `listThreads({ input })`,
//     `updateProject({ identity, input })`, answering
//     `{ success: true, data }` or `{ success: false, errors }`.
//
// graphql-codegen then types the operations (js/gql/graphql.ts). Run
// `npm run codegen`; precommit checks the three files are current.
import fs from "node:fs";
import path from "node:path";
import { buildSchema, getNamedType, isEnumType, isInputObjectType, isListType, isNonNullType, isObjectType, isScalarType } from "graphql";

const here = path.dirname(new URL(import.meta.url).pathname);
const SCHEMA = path.resolve(here, "../../priv/schema.graphql");
const OPERATIONS = path.resolve(here, "../js/core/operations.graphql");
const API = path.resolve(here, "../js/core/api.ts");

// object types that are resources: never expanded inside another type
const RESOURCE_TYPES = new Set(["Project", "Thread", "Turn", "Provider", "Model", "SearchProvider", "Credential", "Watch"]);
// the wrapper of a create / update / destroy mutation
const RESULT_WRAPPER = /Result$/;
// relationships a page reads on a row (scalars of the related row only)
const RELATIONSHIPS = { listModels: ["provider"] };

const schema = buildSchema(fs.readFileSync(SCHEMA, "utf8"));

const upper = (s) => s[0].toUpperCase() + s.slice(1);

function typeName(t) {
  if (isNonNullType(t)) return `${typeName(t.ofType)}!`;
  if (isListType(t)) return `[${typeName(t.ofType)}]`;
  return t.name;
}

/** The selection set of a type: scalars and enums, nested maps expanded, resources left out (except the relationships asked for at the root). */
function selection(type, depth, relationships = []) {
  const named = getNamedType(type);
  if (!isObjectType(named)) return "";
  if (depth > 5) return "";
  const parts = [];
  for (const field of Object.values(named.getFields())) {
    const inner = getNamedType(field.type);
    if (isScalarType(inner) || isEnumType(inner)) {
      parts.push(field.name);
    } else if (isObjectType(inner)) {
      if (RESOURCE_TYPES.has(inner.name) && !relationships.includes(field.name)) continue;
      const sub = selection(field.type, depth + 1);
      if (sub) parts.push(`${field.name} ${sub}`);
    }
  }
  return `{ ${parts.join(" ")} }`;
}

const ops = [];
for (const [kind, root] of [["query", schema.getQueryType()], ["mutation", schema.getMutationType()]]) {
  if (!root) continue;
  for (const field of Object.values(root.getFields())) {
    const args = field.args.map((a) => ({ name: a.name, type: typeName(a.type), json: isJsonInput(a.type) }));
    const named = getNamedType(field.type);
    const wrapped = kind === "mutation" && isObjectType(named) && RESULT_WRAPPER.test(named.name) && "result" in named.getFields();
    const rels = RELATIONSHIPS[field.name] ?? [];
    const sel = wrapped ? `{ result ${selection(named.getFields().result.type, 0, rels)} }` : selection(field.type, 0, rels);
    const vars = args.map((a) => `$${a.name}: ${a.type}`).join(", ");
    const pass = args.map((a) => `${a.name}: $${a.name}`).join(", ");
    const opName = upper(field.name);
    ops.push({
      kind, field: field.name, opName, args, wrapped,
      // input object fields that are Json scalars: the client sends them as JSON strings
      jsonInputs: jsonFields(field.args.find((a) => a.name === "input")),
      document: `${kind} ${opName}${vars ? `(${vars})` : ""} { ${field.name}${pass ? `(${pass})` : ""} ${sel} }`,
    });
  }
}

function isJsonInput(t) {
  const named = getNamedType(t);
  return isScalarType(named) && named.name === "Json";
}

function jsonFields(inputArg) {
  if (!inputArg) return [];
  const named = getNamedType(inputArg.type);
  if (!isInputObjectType(named)) return [];
  return Object.values(named.getFields()).filter((f) => isJsonInput(f.type)).map((f) => f.name);
}

fs.mkdirSync(path.dirname(OPERATIONS), { recursive: true });
fs.writeFileSync(OPERATIONS, `# Generated by scripts/gql-client.mjs from priv/schema.graphql — do not edit.\n\n${ops.map((o) => o.document).join("\n\n")}\n`);

const lines = [
  "// Generated by scripts/gql-client.mjs from priv/schema.graphql — do not edit.",
  "// One function per GraphQL root field, in the shape the hooks call; the",
  "// documents and their types are in js/gql/graphql.ts (graphql-codegen).",
  "import { call, type Call } from \"@/core/gql\";",
  "import * as G from \"@/gql/graphql\";",
  "",
];
for (const o of ops) {
  const Q = `G.${o.opName}${upper(o.kind)}`;
  const V = `${Q}Variables`;
  const shape = JSON.stringify({ kind: o.kind, field: o.field, args: o.args.map((a) => a.name), wrapped: o.wrapped, jsonArgs: o.args.filter((a) => a.json).map((a) => a.name), jsonInputs: o.jsonInputs });
  const data = o.wrapped ? `NonNullable<${Q}["${o.field}"]>["result"]` : `${Q}["${o.field}"]`;
  // call only creates a function; unused APIs need not load their documents.
  lines.push(`export const ${o.field}: Call<${Q}, ${V}, ${data}> = /* @__PURE__ */ call(G.${o.opName}Document, ${shape});`);
}
fs.writeFileSync(API, lines.join("\n") + "\n");
console.log(`${ops.length} operations → ${path.relative(process.cwd(), OPERATIONS)}, ${path.relative(process.cwd(), API)}`);
